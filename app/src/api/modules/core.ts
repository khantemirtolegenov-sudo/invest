/**
 * Общие помощники сервисного слоя. Каждый метод модуля устроен одинаково:
 *   await delay() → проверки прав и валидация → mutate() → возврат КОПИИ.
 * Бизнес-отказ — throw new ApiError('Понятный текст по-русски'): показывается как есть.
 */
export class ApiError extends Error {}

/** Единый ритм асинхронных методов (и место для будущей задержки сети) */
export const delay = (ms = 0) => new Promise<void>((r) => setTimeout(r, ms));

/** Копия сущности наружу: живой объект кэша на странице мутировал бы «базу» мимо синка */
export const copy = <T>(x: T): T => structuredClone(x);
